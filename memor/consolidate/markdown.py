"""Markdown hierarchy projection (Levels 0-2), regenerated from the facts
tables and git-committed on each consolidation run.

Conventions borrowed from prior art:
- directory shape from Letta MemFS: system/ (always-loaded Level 0-1) vs
  reference/ (Level 2-3, on demand)
- in-file format from Basic Memory: YAML frontmatter, observation-category
  tags ([fact]/[decision]/[problem]/[todo]/[lesson]/[state]), and
  `relation_type [[Entity]]` wikilinks.

The SQL tables remain the authoritative temporal record; these files are a
projection of current state, plus a git-committed diff-able history.
"""
from __future__ import annotations

import os
import re
import subprocess
from datetime import timedelta
from pathlib import Path

from ..config import Config
from ..models import slugify, now_utc, parse_ts
from ..store import Store

GENERATED = "<!-- generated by memor — do not edit; regenerate: memor consolidate -->"
_TAG = {
    "state": "state", "configuration": "config", "preference": "preference",
    "problem": "problem", "lesson": "lesson", "todo": "todo",
    "decision": "decision", "architecture": "arch", "fact": "fact",
}


def _frontmatter(d: dict) -> str:
    lines = ["---"]
    for k, v in d.items():
        if v in (None, ""):
            continue
        lines.append(f"{k}: {v}")
    lines.append("---")
    return "\n".join(lines) + "\n\n"


def _tag(kind: str) -> str:
    return _TAG.get(kind, "fact")


def _fact_line(f: dict, with_since: bool = True) -> str:
    since = f" (since {f['valid_from'][:10]})" if with_since and f.get("valid_from") else ""
    conf = f" [{f['confidence']}]" if f.get("confidence") != "confirmed" else ""
    reason = f" — {f['reason']}" if f.get("reason") else ""
    return f"- [{_tag(f['kind'])}] {f['claim']}{conf}{since}{reason} `[{f['id']}]"


def _entity_refs(store: Store) -> list[str]:
    return [e["name"] for e in store.list_entities()]


def _wiki(name: str, known: set[str]) -> str:
    return f"[[{name}]]" if name.lower() in known else name


def _projects(store: Store, cfg: Config) -> dict[str, dict]:
    proj: dict[str, dict] = {}
    for name in {p.name for p in cfg.projects}:
        proj.setdefault(name, {"description": next(
            (p.description for p in cfg.projects if p.name == name), "")})
    for f in store.list_facts(limit=2000):
        p = f.get("scope_project")
        if p:
            proj.setdefault(p, {"description": ""})
        m = f.get("scope_machine")
        if m:
            pass
    return proj


def _machines(store: Store) -> set[str]:
    out = set()
    for f in store.list_facts(limit=2000):
        if f.get("scope_machine"):
            out.add(f["scope_machine"])
    return out


def _episodes_file(p: str | None, eps: list[dict]) -> tuple[str, str]:
    title = (f"# {p} — work episodes" if p else "# Work episodes (unattributed to a project)")
    lines = [GENERATED, "",
             _frontmatter({"type": "episodes", "updated": now_utc(),
                           **({"project": p} if p else {})}),
             title, ""]
    for e in eps:
        lines.append(f"## {e['started_at'][:16]} → {e['ended_at'][:16]} `[{e['id']}]`")
        if e.get("objective"):
            lines.append(f"- objective: {e['objective'][:160]}")
        lines.append(f"- {e['summary']}")
        for l in (e.get("lessons") or [])[:5]:
            lines.append(f"- lesson: {l}")
        lines.append("")
    name = "projects" + "/" + slugify(p) + "/episodes.md" if p else "episodes.md"
    return name, "\n".join(lines) + "\n"


def regenerate(store: Store, cfg: Config, *, commit: bool = True,
               immediate: bool = False) -> list[str]:
    """Rewrite system/ + reference/ trees; git-commit. Returns changed paths.

    Commit policy: files are always rewritten when their *content* changed
    (the `updated:` frontmatter stamp alone does not count as a change, so
    no-op passes rewrite nothing). A git commit is made when `commit` is on
    and either this is an `immediate` call (manual CLI actions) or at least
    `cfg.projection_commit_interval` seconds have passed since the last
    commit (daemon passes; 0 = commit every pass). Files rewritten but not
    yet committed stay on disk and ride the next commit.
    """
    known = set(_entity_refs(store))
    projects = _projects(store, cfg)
    machines = _machines(store)

    root = cfg.data_dir
    system = cfg.system_dir
    ref = cfg.reference_dir
    for d in (system, ref, system / "projects", ref / "projects", ref / "machines"):
        d.mkdir(parents=True, exist_ok=True)

    written: dict[Path, str] = {}

    # ---------------- system/INDEX.md (Level 0) ----------------
    lines = [GENERATED, "", _frontmatter({"type": "index", "updated": now_utc()}),
             "# Memory Index", ""]
    lines.append("## Projects")
    for p in sorted(projects):
        desc = projects[p].get("description") or ""
        n = len(store.list_facts(project=p, status="current", limit=500))
        lines.append(f"- [[{p}]] — {desc} ({n} current facts)".rstrip(" —") if desc
                     else f"- [[{p}]] ({n} current facts)")
    lines += ["", "## Machines"]
    for m in sorted(machines):
        lines.append(f"- [[{m}]]")
    services = [f for f in store.list_facts(kind="state", status="current", limit=500)
                if f["subject"].startswith(("service:", "port:")) or
                f["subject"].endswith(".service")]
    if services:
        lines += ["", "## Active services / ports"]
        for f in services[:25]:
            lines.append(f"- {f['claim']} `[{f['id']}]`")
    open_reviews = store.open_reviews()
    if open_reviews:
        lines += ["", "## Open review items",
                  f"({len(open_reviews)} queued — `memor review`)"]
        for r in open_reviews[:10]:
            lines.append(f"- [{r['category']}] {r['summary'][:100]}")
    written[system / "INDEX.md"] = "\n".join(lines) + "\n"

    # ---------------- Level 1: system/projects/<p>.md ----------------
    for p in sorted(projects):
        facts = store.list_facts(project=p, status="current", limit=500)
        unknown = store.list_facts(project=p, status="unknown", limit=50)
        contrad = store.list_facts(project=p, status="contradictory", limit=50)
        decisions = store.list_decisions(project=p, limit=20)
        comps = sorted({f["scope_component"] for f in facts if f.get("scope_component")})
        lines = [GENERATED, "", _frontmatter(
            {"type": "project", "name": p,
             "updated": now_utc(), "facts": len(facts)}),
            f"# {p}", ""]
        if projects[p].get("description"):
            lines += [f"> {projects[p]['description']}", ""]
        if comps:
            lines += ["## Components", ""]
            for c in comps:
                lines.append(f"- [[{c}]]")
            lines.append("")
        if facts:
            lines += ["## Current state", ""]
            for f in sorted(facts, key=lambda x: (x["scope_component"] or "", x["subject"])):
                lines.append(_fact_line(f))
            lines.append("")
        if decisions:
            lines += ["## Major decisions", ""]
            for d in decisions[:10]:
                alt = f" (alternatives: {', '.join(d['alternatives_considered'])})" \
                    if d["alternatives_considered"] else ""
                reason = f" because {d['reason']}" if d.get("reason") else ""
                mark = "" if d.get("status") == "current" else f" ({d.get('status')})"
                lines.append(f"- [decision] {d['decided_at'][:10]}{mark}: {d['choice']}{alt}{reason} `[{d['id']}]")
            lines.append("")
        problems = [f for f in facts if f["kind"] == "problem"]
        if problems:
            lines += ["## Known problems", ""]
            for f in problems:
                lines.append(_fact_line(f))
            lines.append("")
        if unknown or contrad:
            lines += ["## Uncertain / conflicting", ""]
            for f in (unknown + contrad):
                lines.append(f"- [{_tag(f['kind'])}] ({f['status']}) {f['claim']} `[{f['id']}]`")
            lines.append("")
        rels = []
        for name in ([p] + comps):
            rels.extend(store.relations_for(name, depth=1))
        if rels:
            lines += ["## Relations", ""]
            for r in rels[:20]:
                lines.append(f"- {r['subject']} —{r['relation']}→ {_wiki(r['object'], known)}")
            lines.append("")
        written[system / "projects" / f"{slugify(p)}.md"] = "\n".join(lines) + "\n"

    # ---------------- Level 2: reference/projects/<p>/... ----------------
    for p in sorted(projects):
        pdir = ref / "projects" / slugify(p)
        pdir.mkdir(parents=True, exist_ok=True)
        facts = store.list_facts(project=p, limit=500)
        by_comp: dict[str, list[dict]] = {}
        for f in facts:
            by_comp.setdefault(f.get("scope_component") or "project", []).append(f)
        for comp, cfacts in sorted(by_comp.items()):
            lines = [GENERATED, "", _frontmatter(
                {"type": "component", "name": comp, "project": p, "updated": now_utc()}),
                f"# {comp}", ""]
            current = [f for f in cfacts if f["status"] == "current"]
            history = [f for f in cfacts
                       if f["status"] in ("superseded", "retracted")]
            if current:
                lines += ["## Current", ""]
                for f in current:
                    lines.append(_fact_line(f))
                lines.append("")
            if history:
                lines += ["## History", ""]
                for f in sorted(history, key=lambda x: x.get("valid_until") or "", reverse=True)[:30]:
                    why = f" (reason: {f['reason']})" if f.get("reason") else ""
                    lines.append(f"- {f['valid_from'][:10] if f.get('valid_from') else '?'} → "
                                 f"superseded {f['valid_until'][:10] if f.get('valid_until') else ''}: "
                                 f"{f['claim']}{why} `[{f['id']}]`")
                lines.append("")
            dcs = store.list_decisions(project=p, component=comp, limit=20)
            if dcs:
                lines += ["## Decisions", ""]
                for d in dcs[:20]:
                    alt = f" — alternatives: {', '.join(d['alternatives_considered'])}" \
                        if d["alternatives_considered"] else ""
                    reason = f" — {d['reason']}" if d.get("reason") else ""
                    mark = "" if d.get("status") == "current" else f" ({d.get('status')})"
                    lines.append(f"- [decision] {d['decided_at'][:10]}{mark}: {d['choice']}{alt}{reason} `[{d['id']}]")
                lines.append("")
            rels = store.relations_for(comp, depth=1)
            if rels:
                lines += ["## Relations", ""]
                for r in rels:
                    if r["subject"].lower() == comp.lower():
                        lines.append(f"- {r['relation']} {_wiki(r['object'], known)}")
                    else:
                        lines.append(f"- {_wiki(r['subject'], known)} {r['relation']} this")
                lines.append("")
            target = (pdir / "project.md") if comp == "project" else \
                (pdir / "components" / f"{slugify(comp)}.md")
            if comp != "project":
                target.parent.mkdir(parents=True, exist_ok=True)
            written[target] = "\n".join(lines) + "\n"

    # ---------------- machines ----------------
    for m in sorted(machines):
        facts = store.list_facts(machine=m, status="current", limit=300)
        lines = [GENERATED, "", _frontmatter(
            {"type": "machine", "name": m, "updated": now_utc()}), f"# {m}", ""]
        if facts:
            lines += ["## Current state", ""]
            for f in facts[:80]:
                lines.append(_fact_line(f))
            lines.append("")
        rels = store.relations_for(m, depth=1)
        if rels:
            lines += ["## Runs / hosts", ""]
            for r in rels:
                lines.append(f"- {r['subject']} —{r['relation']}→ {r['object']}")
            lines.append("")
        written[ref / "machines" / f"{slugify(m)}.md"] = "\n".join(lines) + "\n"

    # ---------------- episodes (A3) ----------------
    for p in sorted(projects):
        eps = store.list_episodes(project=p, limit=15)
        if eps:
            name, content = _episodes_file(p, eps)
            target = ref / name
            target.parent.mkdir(parents=True, exist_ok=True)
            written[target] = content
    glob_eps = store.list_episodes(unassigned_only=True, limit=15)
    if glob_eps:
        name, content = _episodes_file(None, glob_eps)
        written[ref / name] = content

    # ---------------- write + prune + commit ----------------
    changed = []
    old_tracked = _tracked_generated(root)
    for path, content in written.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        old = path.read_text() if path.exists() else None
        # The `updated:` stamp changes on every pass; ignore it so no-op
        # passes rewrite nothing and commit nothing.
        if old is not None and _without_stamp(old) == _without_stamp(content):
            continue
        path.write_text(content)
        changed.append(str(path.relative_to(root)))
    for stale in old_tracked:
        sp = root / stale
        if sp.exists() and str(sp.relative_to(root)) not in {str(p.relative_to(root)) for p in written}:
            sp.unlink()
            changed.append("-" + str(sp.relative_to(root)))
    if commit:
        last = store.meta_get("projection.last_commit")
        interval = cfg.projection_commit_interval
        due = immediate or not interval or last is None or \
            parse_ts(now_utc()) - parse_ts(last) >= timedelta(seconds=interval)
        if due and _git_commit(root, _commit_message(store, last)):
            # commits any still-uncommitted projection changes, including
            # files rewritten by earlier (throttled) passes
            store.meta_set("projection.last_commit", now_utc())
    return changed


def _without_stamp(text: str) -> str:
    """File content minus the `updated:` frontmatter line (the only field
    that changes on every regeneration regardless of real changes)."""
    return re.sub(r"^updated: .*$", "", text, flags=re.M)


def _commit_message(store: Store, last: str | None) -> str:
    """Commit message summarizing what happened since the last commit, so
    `git log` on the store tells the day's story in one line."""
    if not last:
        return "memor: initial projection"
    c = store._conn()
    q = lambda sql, a: c.execute(sql, a).fetchone()[0]
    new_f = q("SELECT COUNT(*) FROM facts WHERE status='current' AND valid_from > ?", (last,))
    sup_f = q("SELECT COUNT(*) FROM facts WHERE status='superseded' AND valid_until > ?", (last,))
    decs = q("SELECT COUNT(*) FROM decisions WHERE decided_at > ?", (last,))
    top = c.execute(
        "SELECT subject, COUNT(*) c FROM facts"
        " WHERE (status='current' AND valid_from > ?)"
        "    OR (status='superseded' AND valid_until > ?)"
        " GROUP BY subject ORDER BY c DESC, subject LIMIT 6",
        (last, last)).fetchall()
    open_r = len(store.open_reviews())
    llm_cur = store.meta_get("llm.cursor") or "1970-01-01T00:00:00Z"
    llm_seen = set((store.meta_get("llm.seen") or "").splitlines())
    pending = len([e for e in store.events_since(llm_cur, limit=5000)
                   if e["id"] not in llm_seen and e["source"] != "memor"])
    msg = (f"memor projection {now_utc()[:16]}: +{new_f} facts, "
           f"{sup_f} superseded, {decs} decisions since {last[:16]}")
    parts = []
    if top:
        parts.append("top: " + ", ".join(f"{s} ({n})" for s, n in top))
    if open_r:
        parts.append(f"{open_r} review(s) open")
    if pending:
        parts.append(f"llm queue: {pending} pending")
    if parts:
        msg += "\n" + " | ".join(parts)
    return msg


def _tracked_generated(root: Path) -> list[str]:
    out = []
    for d in ("system", "reference"):
        base = root / d
        if not base.exists():
            continue
        for f in base.rglob("*.md"):
            try:
                head = f.read_text(errors="ignore")[:200]
            except OSError:
                continue
            if GENERATED.split("—")[0].strip() in head:
                out.append(str(f.relative_to(root)))
    return out


def _git_commit(root: Path, msg: str) -> bool:
    try:
        subprocess.run(["git", "-C", str(root), "add", "-A", "system", "reference"],
                       check=True, capture_output=True)
        r = subprocess.run(["git", "-C", str(root), "diff", "--cached", "--quiet"])
        if r.returncode == 0:
            return False
        files = subprocess.run(
            ["git", "-C", str(root), "diff", "--cached", "--name-only"],
            check=True, capture_output=True, text=True).stdout.strip().splitlines()
        if len(files) > 1:
            msg = msg + f" ({len(files)} files)"
        subprocess.run(
            ["git", "-C", str(root), "-c", "user.name=memor", "-c", "user.email=memor@local",
             "commit", "-m", msg],
            check=True, capture_output=True,
        )
        return True
    except (subprocess.CalledProcessError, FileNotFoundError):
        return False