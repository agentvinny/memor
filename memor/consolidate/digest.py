"""G2: the periodic human digest — one file that pulls the human into the
review loop without any querying: what changed since the last digest, open
items, surprises, and the LLM queue state. Written to system/DIGEST.md
(git-committed like the rest of the projection) by `memor digest` and by
the daemon's digest thread (digest_interval, 0 disables)."""
from __future__ import annotations

from ..models import now_utc
from ..store import Store, data_dir_size

GENERATED = ("<!-- generated by memor digest — do not edit; "
             "regenerate: memor digest -->")


def _since_stamp(store: Store) -> str:
    return store.meta_get("digest.since") or now_utc()


def build_digest(store: Store, cfg, *, immediate: bool = False) -> str:
    since = _since_stamp(store)
    cfgj = cfg
    lines = [GENERATED, "",
             f"# Digest — {now_utc()}",
             f"_since {since}_", ""]

    # strict comparisons: second-granular timestamps mean a fact landing exactly
    # on the window edge must not be counted in the NEXT window too
    all_facts = store.list_facts(limit=500)
    cur_new = [f for f in all_facts if f["status"] == "current"
               and (f.get("valid_from") or "") > since]
    superseded = [f for f in all_facts if f["status"] == "superseded"
                  and (f.get("valid_until") or "") > since]
    lines += ["## Changes since last digest", ""]
    if cur_new or superseded:
        for f in cur_new[:40]:
            why = f" (reason: {f['reason']})" if f.get("reason") else ""
            lines.append(f"- new: {f['claim'][:140]}{why} "
                         f"`[{f['scope_project'] or '∅'}/{f['id']}]`")
        for f in superseded[:40]:
            lines.append(f"- changed: {f['claim'][:140]} → "
                         f"{f.get('valid_until', '?')[:10]} `[{f['id']}]`")
    else:
        lines.append("(no state changes)")

    lines += ["", "## Decisions", ""]
    decs = [d for d in store.list_decisions(limit=100)
            if (d.get("decided_at") or "") > since and d.get("status") == "current"]
    if decs:
        for d in decs[:20]:
            reason = f" — {d['reason']}" if d.get("reason") else ""
            lines.append(f"- {d['decided_at'][:10]}: {d['choice']}{reason} `[{d['id']}]`")
    else:
        lines.append("(none)")

    lines += ["", "## Surprises & open items", ""]
    reviews = store.open_reviews()
    surprises = [r for r in reviews if r["category"] == "surprise"]
    other = [r for r in reviews if r["category"] != "surprise"]
    if surprises:
        for r in surprises[:15]:
            lines.append(f"- [surprise] {r['summary']} `[{r['id']}]`")
    if other:
        for r in other[:15]:
            lines.append(f"- [review:{r['category']}] {r['summary']} `[{r['id']}]`")
    uncertain = [f for f in store.list_facts(limit=500)
                 if f["status"] in ("unknown", "contradictory")]
    if uncertain:
        for f in uncertain[:15]:
            lines.append(f"- [{f['status']}] {f['claim'][:140]} `[{f['id']}]`")
    if not (surprises or other or uncertain):
        lines.append("(none — memory is clean)")

    lines += ["", "## Activity", ""]
    by_src = {}
    for e in store.events_since(since, limit=5000):
        if e.get("source") == "memor":
            continue
        by_src[e["source"]] = by_src.get(e["source"], 0) + 1
    if by_src:
        lines.append("events: " + "  ".join(
            f"{k}={v}" for k, v in sorted(by_src.items(), key=lambda x: -x[1])[:10]))
    eps = store.list_episodes(since=since, limit=10)
    if eps:
        lines.append("")
        for e in eps:
            lines.append(f"- episode {e['started_at'][:10]}→{e['ended_at'][:10]} "
                         f"[{e['project'] or '∅'}]: {e['summary'][:120]} `[{e['id']}]`")
    if not by_src and not eps:
        lines.append("(quiet period)")

    # store-size alert (threshold: cfg.max_store_size_bytes, 0 = off)
    size = data_dir_size(cfg.data_dir)
    lines += ["", "## Store size", ""]
    if cfg.max_store_size_bytes > 0 and size > cfg.max_store_size_bytes:
        lines.append(
            f"**WARNING: {size / 1e9:.2f} GiB used — exceeds the "
            f"{cfg.max_store_size_bytes / 1e9:.0f} GiB threshold.** "
            f"Options: `memor compact --dry-run` (retires old, already-"
            f"consolidated evidence) or raise `max_store_size_bytes` in memor.json.")
    elif cfg.max_store_size_bytes > 0:
        lines.append(f"{size / 1e6:.0f} MiB used (alert threshold "
                     f"{cfg.max_store_size_bytes / 1e9:.0f} GiB)")
    else:
        lines.append(f"{size / 1e6:.0f} MiB used (size alert disabled)")

    try:
        from .extract import extractor_for
        from .apply import llm_pending_count
        if cfg.llm_enabled:
            name, _ = extractor_for(cfg)
            lines += ["", "## LLM queue", ""]
            lines.append(f"provider: {name} — pending records: {llm_pending_count(store)}"
                         "  (`memor llm sync` when the server is up)")
    except Exception:
        pass

    text = "\n".join(lines) + "\n"
    path = cfg.system_dir / "DIGEST.md"
    cfg.system_dir.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    store.meta_set("digest.since", now_utc())
    # Same commit policy as the projection: manual `memor digest` commits
    # now; the daemon's daily digest only commits when the shared
    # projection-commit window is due (it then also carries any pending
    # projection changes, since the commit stages the whole tree).
    try:
        from datetime import timedelta
        from ..models import parse_ts
        from .markdown import _git_commit
        last = store.meta_get("projection.last_commit")
        interval = cfg.projection_commit_interval
        due = immediate or not interval or last is None or \
            parse_ts(now_utc()) - parse_ts(last) >= timedelta(seconds=interval)
        if due and _git_commit(cfg.data_dir, f"memor digest {now_utc()[:16]}"):
            store.meta_set("projection.last_commit", now_utc())
    except Exception:
        pass
    return str(path)