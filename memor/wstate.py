"""Workspace state: the structured, workspace-scoped "what is true right
now" surface (open items, problems, decisions, conventions, key commands,
workflows, checklists, practices, notes).

The store table (`workspace_state`) is the source of truth: one row per
(workspace, category, subject) key while active, with status transitions
(resolved/retired/superseded) and provenance (which session window wrote
it last). Two writer classes:
  - the agent, as-you-go, via the MCP tools / `memor state` CLI
    (conventions, commands, workflows, checklists, ...);
  - the flush worker, autonomously: each window's extracted
    decisions/problems/open_items are PROMOTED into the state (deduped on
    the key; re-promotion updates the active row in place).

Read projections:
  - `state_document` — the rendered markdown. Rides the SessionStart
    injection envelope (active section, at boot — the catch-up moment)
    and is the on-demand mid-session fetch (`memor state show`, MCP
    `memory_get_workspace_state`).
  - `project_state_file` — OPT-IN file projection into the workspace's
    AGENTS.local.md between machine markers (config
    `session_state_project_file`, or explicit `memor state project`).
    Off by default on purpose: that file is DSH's instruction channel,
    and DSH re-projects any change into every running session as an
    "instruction update" — a churning machine surface riding that
    channel is a per-window token tax. The file, when enabled, is a
    regeneration; never hand-edit inside the markers.
"""
from __future__ import annotations

import json
from pathlib import Path

# Render order = document order. Unknown categories (the category is an
# open string) sort after these, alphabetically.
CATEGORY_ORDER = [
    ("open_item", "Open items"),
    ("problem", "Problems (active)"),
    ("decision", "Decisions"),
    ("convention", "Conventions"),
    ("practice", "Best practices"),
    ("command", "Key commands"),
    ("workflow", "Workflows"),
    ("checklist", "Checklists"),
    ("note", "Notes"),
]
CATEGORY_LABELS = dict(CATEGORY_ORDER)
# file projection size discipline: per-category cap; overflow stays in the
# store (drill via `memor state show`), the file is the HOT set
FILE_CATEGORY_CAP = 25

BEGIN_MARKER = "<!-- memor:workspace-state:begin"
END_MARKER = "memor:workspace-state:end -->"

_STATE_HEADER = (
    f"{BEGIN_MARKER} — machine-generated by memor (session memory).\n"
    "     Do not edit inside the markers: `memor state add|set ...` or the\n"
    "     MCP tools (memory_workspace_state_add / memory_workspace_state_set).\n"
    "     The store is the source of truth; this section is regenerated.\n")


def state_document(store, workspace: str,
                   recently_resolved: int = 5) -> str:
    """The workspace's current state as one self-explanatory markdown
    document (active items grouped by category, then what just closed).
    Pure function of the store."""
    rows = store.workspace_state_current(workspace, recently_resolved)
    stale = store.workspace_state_stale(workspace)
    if not rows and not stale:
        return f"## Workspace state — {workspace}\n\n(nothing recorded yet)\n"
    active = [r for r in rows if r["status"] == "active"]
    closed = [r for r in rows if r["status"] in ("resolved", "retired")]
    by_cat: dict = {}
    for r in active:
        by_cat.setdefault(r["category"], []).append(r)
    lines = [f"## Workspace state — {workspace}", "",
             "Current open items, problems, decisions, and standing "
             "knowledge for this workspace — machine-maintained by memor "
             "(write via `memor state` or the MCP tools).",
             "Keep this list true: close items that are done or no longer "
             "hold — `memor state set <id> resolved` (or retired), or "
             "`memory_workspace_state_set`; multiple ids per call.", ""]
    ordered = [c for c, _ in CATEGORY_ORDER if c in by_cat]
    ordered += sorted(c for c in by_cat if c not in CATEGORY_LABELS)
    for cat in ordered:
        items = by_cat[cat]
        label = CATEGORY_LABELS.get(cat, cat.replace("_", " ").title())
        lines.append(f"### {label} ({len(items)})")
        lines.append("")
        shown = items[:FILE_CATEGORY_CAP]
        for r in shown:
            lines.append(_render_item(r))
        if len(items) > FILE_CATEGORY_CAP:
            lines.append(f"… +{len(items) - FILE_CATEGORY_CAP} more "
                         "(memor state show)")
        lines.append("")
    if closed:
        lines.append(f"### Recently handled ({len(closed)})")
        lines.append("")
        for r in closed:
            lines.append(_render_item(r, closed=True))
        lines.append("")
    if stale:
        lines.append(f"### Stale ({len(stale)}) — untouched for a while; "
                     "revive with `memor state set <id> active`")
        lines.append("")
        for r in stale:
            lines.append(f"- **{r['subject']}** [{r['id']}]")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def state_listing(store, workspace: str, *, category: str | None = None,
                  status: str | None = None, limit: int | None = None,
                  age_days: float | None = None) -> str:
    """P2 filtered listing (the `memor state show --...` flat view):
    one line per matching row, id first — the curation handle. Most
    recently handled first."""
    rows = store.workspace_state_list(
        workspace, category=category, status=status,
        limit=limit, age_days=age_days)
    if not rows:
        return "(no matching state rows)\n"
    out = []
    for r in rows:
        out.append(f"[{r['id']}] ({r['status']}) ({r['category']}) "
                   f"{r['subject']} — {r['body']} ({r['updated_at'][:10]})")
    return "\n".join(out) + "\n"


def _render_item(r: dict, closed: bool = False) -> str:
    # the id on every line is load-bearing: the agent cures items via
    # `memor state set <id> resolved|retired|...` (or the MCP tool) and the
    # rendered document is the only place it sees the ids
    src = f" ({r['source_span']})" if r.get("source_span") else ""
    stamp = f" — {r['status']} {r['updated_at'][:10]}" if closed else ""
    return f"- **{r['subject']}** — {r['body']}{src} [{r['id']}]{stamp}"


# P3 envelope layout: what NEEDS doing first, standing knowledge last.
# Caps keep the boot injection bounded no matter how the store grows
# (overflow stays one `memor state show` away).
SECTION_CAPS = (("Open", 15), ("Recent failures", 5),
                ("Recent decisions", 10), ("Standing knowledge", 10))
_DECAYING = ("open_item", "problem")
# how long a closed problem row stays visible in the envelope as 'recently
# failed' negative knowledge — the same horizon `memor state show
# --age-days 14` uses for triage
FAILURE_HORIZON_DAYS = 14


def state_section(store, workspace: str) -> str:
    """The workspace's state for the SessionStart envelope (P3):
    actionable-first and bounded — Open (open items + problems,
    most-recently-handled first), Recent failures (closed problem rows
    inside the horizon — 'we tried this, it failed, here's how it was
    handled'), recent decisions, then standing knowledge
    (conventions/commands/workflows/..., if any). Stale rows are
    excluded. '' when the workspace has neither active state nor recent
    failures."""
    rows = store.workspace_state_current(workspace, 0)
    active = [r for r in rows if r["status"] == "active"]
    # the negative-knowledge bucket: active problems are already in
    # Open, so this carries only what JUST got handled
    failures = store.workspace_state_list(
        workspace, category="problem", status="resolved",
        age_days=FAILURE_HORIZON_DAYS)
    failures += store.workspace_state_list(
        workspace, category="problem", status="retired",
        age_days=FAILURE_HORIZON_DAYS)
    if not active and not failures:
        return ""
    buckets: dict[str, list[dict]] = {}
    for r in active:
        if r["category"] in _DECAYING:
            buckets.setdefault("Open", []).append(r)
        elif r["category"] == "decision":
            buckets.setdefault("Recent decisions", []).append(r)
        else:
            buckets.setdefault("Standing knowledge", []).append(r)
    if failures:
        buckets["Recent failures"] = failures  # already rev-desc
    for k in buckets:
        buckets[k].sort(key=lambda r: -r["rev"])  # most recently handled
    lines = [f"## Workspace state — {workspace}", "",
             "Current state for this workspace (machine-maintained by "
             "memor). Keep it true: close what is done or no longer "
             "holds — `memor state set <id> resolved` (or retired) or "
             "`memory_workspace_state_set`; multiple ids per call.", ""]
    for title, cap in SECTION_CAPS:
        items = buckets.get(title, [])
        if not items:
            continue
        lines.append(f"### {title} ({len(items)})")
        lines.append("")
        for r in items[:cap]:
            lines.append(_render_item(r, closed=(title == "Recent failures")))
        if len(items) > cap:
            lines.append(f"… +{len(items) - cap} more (`memor state show`)")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def project_state_file(workspace: str, store,
                       recently_resolved: int = 5) -> Path | None:
    """Render the state document and write it between the machine markers
    in <workspace>/AGENTS.local.md (created if absent). OPT-IN surface
    (session_state_project_file / explicit `memor state project`): DSH
    injects this file at session start and re-projects any change into
    running sessions as an instruction update — so call it only when the
    file projection is actually wanted. Returns the file path when
    (re)written, None when the content was already current. Never
    touches content outside the markers."""
    path = Path(workspace) / "AGENTS.local.md"
    doc = state_document(store, workspace, recently_resolved)
    block = f"{_STATE_HEADER}\n{doc}\n<!-- {END_MARKER}\n"
    old = path.read_text() if path.exists() else None
    if old is None:
        new = (f"# {Path(workspace).name} — local notes\n"
               "\n<!-- machine-managed section below (memor workspace "
               f"state) -->\n\n{block}")
    else:
        new = _replace_block(old, block)
    if old is not None and old == new:
        return None
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(new)
    return path


def _replace_block(old: str, block: str) -> str:
    """Replace the region between the markers (or append the block)."""
    b = old.find(BEGIN_MARKER)
    if b != -1:
        e = old.find(END_MARKER, b)
        if e != -1:
            end = e + len(END_MARKER)
            # keep whatever newline follows the end marker
            rest = old[end:].lstrip("\n")
            suffix = "\n" + rest if rest else ""
            return old[:b] + block + suffix
    return old.rstrip("\n") + "\n\n" + block


def promote_from_summary(store, summary: dict, get_emb=None,
                         threshold: float = 0.80,
                         threshold_ref: float = 0.90) -> int:
    """Autonomous promotion: lift a window's structured extraction into
    workspace state. `summary` is a summaries row (level 1 with a
    workspace, span, session and the decisions/problems/open_items JSON
    columns). Idempotent: re-promoting the same content from the same
    span changes nothing. Returns the number of rows actually moved
    (created, or body/provenance updated). Never raises for content
    problems (worker path).

    `get_emb` (P1 backstop): a callable returning the embedder or None,
    invoked at most once — lazily, only when a candidate does not match
    an exact key. With it, a candidate whose `subject — body` sits at or
    above the category's cosine threshold against an active row of the
    same workspace+category updates that row in place instead of creating
    a paraphrase-duplicate. `threshold` applies to decaying categories
    (open_item/problem); `threshold_ref` to the reference categories —
    related-but-distinct decisions share enough vocabulary to reach
    ~0.87 (live-measured), so they need the stricter bar. None (or
    embedder unavailable) falls back to exact-key promotion only."""
    ws = summary.get("workspace")
    if not ws:
        return 0
    span = summary.get("span")
    sid = summary.get("session")
    dedup = _DedupIndex(store, get_emb) if get_emb is not None else None
    n = 0
    for d in _json_list(summary.get("decisions")):
        if not isinstance(d, dict):
            continue
        subject = str(d.get("subject") or "").strip()
        if not subject:
            continue
        body = str(d.get("choice") or "").strip()
        if d.get("reason"):
            body = f"{body} — {d['reason']}".strip()
        n += _promote(store, ws, "decision", subject, body or subject,
                      sid, span, dedup, threshold_ref)
    for col, cat in (("problems", "problem"),
                     ("open_items", "open_item")):
        for line in _json_list(summary.get(col)):
            s = str(line).strip()
            if s:
                n += _promote(store, ws, cat, s, s, sid, span, dedup,
                             threshold)
    return n


class _DedupIndex:
    """P1 backstop, per promotion batch: the workspace's active rows,
    embedded (via the shared lazy cache) only when a candidate actually
    needs the comparison."""

    def __init__(self, store, get_emb):
        self.store = store
        self.get_emb = get_emb
        self.emb = None
        self._resolved = False
        self._vecs: dict[tuple[str, str], dict] = {}

    def merge_target(self, ws: str, cat: str, subject: str, body: str,
                     threshold: float) -> dict | None:
        """The active row (same ws+category) most similar to the
        candidate, when its cosine is at/above `threshold`; else None."""
        import numpy as np
        from .search import ensure_cached_embeddings
        if not self._resolved:
            self._resolved = True
            self.emb = self.get_emb()
        if self.emb is None:
            return None
        key = (ws, cat)
        if key not in self._vecs:
            rows = [r for r in self.store.workspace_state_current(ws, 0)
                    if r["category"] == cat and r["status"] == "active"]
            have = ensure_cached_embeddings(
                self.store, self.emb, "state",
                {r["id"]: f"{r['subject']} — {r['body']}" for r in rows})
            self._vecs[key] = {
                r["id"]: np.frombuffer(have[r["id"]], dtype=np.float32)
                for r in rows}
        vecs = self._vecs[key]
        if not vecs:
            return None
        cvec = np.array(self.emb.embed([f"{subject} — {body}"])[0],
                       dtype=np.float32)
        n = float(np.linalg.norm(cvec)) or 1.0
        cvec = cvec / n
        best_id, best = None, -2.0
        for rid, v in vecs.items():
            c = float(v @ cvec)
            if c > best:
                best, best_id = c, rid
        if best >= threshold:
            return self.store.workspace_state_get(best_id)
        return None


def _json_list(v) -> list:
    """The attached columns are JSON text in the store (None when the
    window had none); accept a parsed list too (tests)."""
    if not v:
        return []
    if isinstance(v, str):
        try:
            v = json.loads(v)
        except Exception:  # noqa: BLE001 — corrupt column = no promotion
            return []
    return v if isinstance(v, list) else []


def _promote(store, ws: str, cat: str, subject: str, body: str,
             sid: str | None, span: str | None, dedup: "_DedupIndex | None" = None,
             threshold: float = 0.80) -> int:
    """Upsert one item; 1 when the row was created or actually changed
    by this promotion, 0 for an identical re-promotion. With `dedup`
    (P1 backstop), a candidate that does not match an exact key but
    resembles an active row of the same category updates that row in
    place instead of creating a paraphrase-duplicate."""
    before = store.workspace_state_active(ws, cat, subject)
    if before is None and dedup is not None:
        target = dedup.merge_target(ws, cat, subject, body, threshold)
        if target is not None:
            row = store.workspace_state_upsert(
                ws, cat, target["subject"], body,
                source_session=sid, source_span=span)
            return int(row["id"] == target["id"]
                       and (row["body"] != target["body"]
                            or row["source_span"] != target["source_span"]))
    row = store.workspace_state_upsert(ws, cat, subject, body,
                                       source_session=sid, source_span=span)
    if before is None:
        return 1
    return int(before["body"] != row["body"]
               or before["source_span"] != row["source_span"])


def refresh(workspace: str, store) -> Path | None:
    """Explicit file projection (kept as the named helper for `memor
    state project` and for configs that turn the file on)."""
    return project_state_file(workspace, store)
